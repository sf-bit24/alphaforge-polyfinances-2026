def make_profile(raw: dict) -> dict:
    return validate(_merge(DEFAULTS, raw))


def save_yaml(raw: dict, name: str) -> Path:
    p = PROFILES / f"{name}.yaml"
    p.write_text("# GENERATED by analysis/amira scripts - Amira (fictional persona). Simulation only.\n"
                 + yaml.safe_dump(raw, sort_keys=False, allow_unicode=True))
    return p


def run(raw: dict, out_sub: str, **kw) -> dict:
    prof = make_profile(raw)
    return run_profile(prof, out_dir=RESULTS / out_sub, verbose=False, **kw)


def rel(path: str | Path) -> str:
    return str(Path(path).resolve().relative_to(BT))


def write_json(obj, path: Path, inputs: list[str] | None = None) -> str:
    """Analysis-level trace: adds engine/data hashes and the engine traces it was computed from."""
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = {"disclaimer": "Simulation historique uniquement. Pas un conseil financier. Les lignes ORACLE sont "
                             "a posteriori (hindsight=True) et non investissables.",
               "engine_sha256": engine_hash(), "data_version": data_version(), "inputs": inputs or [],
               "result": obj}
    path.write_text(json.dumps(payload, indent=1, default=_default))
    return rel(path)


def _default(o):
    if isinstance(o, (np.floating,)):
        return None if not np.isfinite(o) else float(o)
    if isinstance(o, (np.integer,)):
        return int(o)
    if isinstance(o, (np.bool_,)):
        return bool(o)
    if isinstance(o, (pd.Timestamp,)):
        return str(o.date())
    if isinstance(o, pd.DataFrame):
        return o.reset_index().to_dict(orient="records")
    if isinstance(o, pd.Series):
        return o.to_dict()
    return str(o)


def per_strategy_stats(rows: pd.DataFrame, q: float = 0.10) -> pd.DataFrame:
    ex = rows[~rows["hindsight"]]
    g = ex.groupby("strategy")
    return pd.DataFrame({
        "n": g.size(),
        "real_p10": g["ann_real_return"].quantile(q),
        "real_median": g["ann_real_return"].median(),
        "real_worst": g["ann_real_return"].min(),
        "vol_median": g["volatility"].median(),
        "maxdd_worst": g["max_drawdown"].max(),
        "maxdd_p90": g["max_drawdown"].quantile(0.9),
        "underwater_worst": g["max_underwater_months"].max(),
        "cvar5_worst": g["cvar_5"].max(),
        "missed_rate": g["missed_target"].apply(lambda s: float(np.mean(s.astype(float)))),
        "breach_rate": g["n_breaches"].apply(lambda s: float(np.mean(s > 0))),
    })
