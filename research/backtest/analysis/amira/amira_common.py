SECTORS = ["US_IND_NODUR", "US_IND_DURBL", "US_IND_MANUF", "US_IND_ENRGY", "US_IND_CHEMS", "US_IND_BUSEQ",
           "US_IND_TELCM", "US_IND_UTILS", "US_IND_SHOPS", "US_IND_HLTH", "US_IND_MONEY", "US_IND_OTHER"]
